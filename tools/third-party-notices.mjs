// Writes THIRD-PARTY-NOTICES.txt: the license of every crate compiled into
// the shipped Windows binaries (hush.exe, hush-setup.exe, hush_apo.dll and
// the installer), with each crate's own license files. Dev and build
// dependencies are not shipped and are left out. Identical license texts
// are printed once, followed by the crates that use them.
//
//   node tools/third-party-notices.mjs
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const metadata = JSON.parse(
  execFileSync(
    "cargo",
    ["metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-pc-windows-msvc"],
    { maxBuffer: 1 << 28 },
  ),
);
const packages = new Map(metadata.packages.map((p) => [p.id, p]));
const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
const roots = metadata.workspace_members;

// Walk normal (runtime) dependency edges only.
const shipped = new Set();
const pending = [...roots];
while (pending.length) {
  const id = pending.pop();
  if (shipped.has(id)) continue;
  shipped.add(id);
  for (const dep of nodes.get(id)?.deps ?? []) {
    if (dep.dep_kinds.some((k) => k.kind === null)) pending.push(dep.pkg);
  }
}

const MIT = `Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE.`;

const groups = new Map();
const crates = [];
for (const id of shipped) {
  if (roots.includes(id)) continue;
  const pkg = packages.get(id);
  const dir = dirname(pkg.manifest_path);
  const files = readdirSync(dir)
    .filter((f) => /^(LICEN[CS]E|COPYING|NOTICE|COPYRIGHT|UNLICENSE)/i.test(f))
    .sort();
  if (pkg.license_file) files.push(pkg.license_file);
  // Bundled fonts carry their licenses next to the font files (egui).
  try {
    for (const f of readdirSync(join(dir, "fonts")).sort()) {
      if (/\.txt$/i.test(f)) files.push(join("fonts", f));
    }
  } catch {}
  crates.push(`${pkg.name} ${pkg.version}  (${pkg.license ?? "see license file"})`);
  const texts = [...new Set(files)].map((f) => readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim());
  let key = texts.join("\n\n-----\n\n");
  if (!texts.length && /MIT/.test(pkg.license ?? "")) {
    // The crate package omits its license file: reproduce the MIT terms it
    // is offered under, attributed to its listed authors.
    const holders = pkg.authors.join(", ") || `the ${pkg.name} authors`;
    key = `MIT License (offered under ${pkg.license})\n\nCopyright (c) ${holders}\n\n${MIT}`;
  } else if (!texts.length) {
    key = `License: ${pkg.license ?? "unknown"} (no license file in the crate package)`;
  }
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(`${pkg.name} ${pkg.version}`);
}
crates.sort();

const rule = "=".repeat(78);
let out = `Hush third-party notices

Hush includes the software below. Each component remains under its own
license. Generated by tools/third-party-notices.mjs from Cargo.lock.

Bundled models
--------------
* DeepFilterNet 3 (DeepFilterNet3_onnx.tar.gz), embedded in hush_apo.dll
  through the deep_filter crate. From https://github.com/Rikorose/DeepFilterNet
  (v0.5.6), MIT or Apache-2.0. Copyright (c) 2021 Hendrik Schröter.
  Paper: H. Schröter et al., "DeepFilterNet: Perceptually Motivated Real-Time
  Speech Enhancement", Interspeech 2023.
* RNNoise model weights, embedded through the nnnoiseless crate (a Rust port
  of RNNoise by Jean-Marc Valin / Xiph.Org Foundation), BSD-3-Clause.
  Only the speech-probability output is used.

Components (${crates.length})
${"-".repeat(13 + String(crates.length).length)}
${crates.join("\n")}
`;
for (const [text, users] of [...groups].sort((a, b) => a[1][0].localeCompare(b[1][0]))) {
  out += `\n${rule}\n${users.sort().join(", ")}\n${rule}\n\n${text}\n`;
}
writeFileSync("THIRD-PARTY-NOTICES.txt", out.replace(/\n/g, "\r\n"));
console.log(`THIRD-PARTY-NOTICES.txt: ${crates.length} crates, ${groups.size} distinct license texts`);
